export const textWidth = (s, sc = 1) => s.length * 6 * sc - sc;

function glyphs(s, x, y, col, sc) {
  g.fillStyle = col;
  for (let i = 0; i < s.length; i++) {
    const cols = FONT[s[i]];
    if (!cols) continue;
    for (let c = 0; c < 5; c++) for (let r = 0; r < 7; r++) {
      if ((cols[c] >> r) & 1) g.fillRect(x + (i * 6 + c) * sc, y + r * sc, sc, sc);
    }
  }
}

/** Draws text. Options: s (scale), align ('c' or 'r'), ol (outline colour). */
export function txt(str, x, y, col, opt = {}) {
  const s = String(str).toUpperCase(), sc = opt.s || 1;
  if (opt.align === 'c') x -= Math.floor(textWidth(s, sc) / 2);
  if (opt.align === 'r') x -= textWidth(s, sc);
  x = Math.round(x);
  y = Math.round(y);
  if (opt.ol) for (const [a, b] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) glyphs(s, x + a * sc, y + b * sc, opt.ol, sc);
  glyphs(s, x, y, col, sc);
}
